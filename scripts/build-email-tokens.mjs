// Writes emails/tokens.ts: the literal light and dark values of the semantic color tokens the emails use,
// resolved from the design system's tokens.json. Email HTML can't use CSS variables reliably, so emails
// are the one place literal colors are allowed. Re-run after scripts/sync-design-system.sh.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, "packages/design-system/tokens.json"), "utf8")).color.tokens;
const byName = Object.fromEntries(tokens.map((t) => [t.name, t.value]));
const resolve = (v) => (typeof v === "string" && v.startsWith("{") ? resolve(byName[v.slice(1, -1)]) : v);
const used = [
  "bg", "surface", "surface-sunken", "surface-brand", "line", "line-strong", "ink", "ink-muted", "ink-subtle",
  "ink-brand", "ink-on-brand", "link", "action", "on-action", "action-strong", "on-action-strong", "highlight",
  "success", "success-soft", "neutral-soft", "logo-mark", "logo-ink",
];
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const pick = (theme) => used.map((n) => `  ${camel(n)}: "${resolve(byName[n][theme])}",`).join("\n");
const src = `/* Generated by scripts/build-email-tokens.mjs from packages/design-system/tokens.json. Do not edit. */

export const light = {
${pick("light")}
} as const;

export const dark = {
${pick("dark")}
} as const;

export type EmailColors = { readonly [K in keyof typeof light]: string };
`;
fs.writeFileSync(path.join(ROOT, "emails/tokens.ts"), src);
console.log("Wrote emails/tokens.ts");
